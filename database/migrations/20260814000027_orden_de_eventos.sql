-- ============================================================
-- ObraCtrl · 0027 · Los eventos de una incidencia tienen orden propio
-- Spec §11.3 F (workflow de incidencia) · §11.7 · Fase 14 del ROADMAP.
--
-- EL SÍNTOMA: UNA PRUEBA QUE FALLABA UNA DE CADA TANTAS
--
-- `test_flujo_completo_deja_la_incidencia_cerrada` afirma que los eventos de
-- una incidencia salen en orden —programar, atender, solicitar_cierre, cerrar—
-- ordenando por `fecha`. Falló una vez con un orden aleatorio de
-- `pytest-randomly` y pasaba siempre en orden fijo, que es la peor forma de un
-- bug: se ignora hasta que rompe en CI sin que nadie haya tocado nada.
--
-- LA CAUSA: `timestamptz` NO ES UN NÚMERO DE SECUENCIA
--
-- Cuatro eventos que se escriben en el mismo tick del reloj comparten `fecha`,
-- y entonces `order by fecha` no tiene con qué desempatar: Postgres devuelve el
-- orden que le convenga. En Windows, donde la resolución del reloj es peor que
-- en Linux, el empate es más probable — y por eso pasaba en CI y fallaba en
-- local, o al revés, según el día.
--
-- Es exactamente el mismo problema que la 0019 resolvió en `carga_snapshot`
-- ("`created_at` no sirve porque `now()` es constante dentro de la
-- transacción"), y aquí ni siquiera hace falta que sea la misma transacción:
-- basta con que dos escrituras caigan en el mismo milisegundo.
--
-- LA SOLUCIÓN: UNA SECUENCIA, NO UN RELOJ
--
-- `orden` es un `identity` de la tabla: crece con cada inserción y no depende
-- de ningún reloj. `fecha` se queda porque responde otra pregunta —cuándo pasó,
-- que es lo que se muestra—; `orden` responde en qué secuencia, que es lo que
-- se ordena. Confundirlas fue el bug.
--
-- Los huecos que deja la secuencia ante un rollback no importan: lo único que
-- se le pide es que sea monótona.
-- ============================================================

alter table incidencia_evento
  add column orden bigint generated by default as identity;

comment on column incidencia_evento.orden is
  'Secuencia de inserción dentro de la tabla. Es lo que se ordena; `fecha` es lo que se muestra. Un `timestamptz` no desempata: dos eventos del mismo tick comparten valor (§11.3 F).';

create index ix_incidencia_evento_orden
  on incidencia_evento (org_id, incidencia_id, orden);
